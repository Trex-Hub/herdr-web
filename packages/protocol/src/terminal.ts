import { z } from "zod";

// --- the terminal socket ----------------------------------------------------
// One WebSocket per terminal view. Bytes travel as binary messages with a one-byte tag;
// everything else is JSON text. See PROTOCOL.md ("Terminal socket").

/** Path prefix of the terminal socket; the terminal's address follows (`/api/terminal/t7`, `/api/terminal/cachyos/t7`). */
export const TERMINAL_SOCKET_PREFIX = "/api/terminal/";

/** A terminal address as the terminal socket path accepts it: `t7`, `t1b` (core counts in base 32 after t31) or `machine/t7`. */
const ADDRESS = /^(?:[A-Za-z0-9][A-Za-z0-9._-]{0,63}\/)?t[0-9a-z]{1,9}$/;

export function isTerminalAddress(address: string): boolean {
  return ADDRESS.test(address);
}

/** The socket path for an address (each part percent-encoded; the slash of a remote address stays). */
export function terminalSocketPath(address: string): string {
  return TERMINAL_SOCKET_PREFIX + address.split("/").map(encodeURIComponent).join("/");
}

/** The address a socket path asks for, or null when the path is not a terminal socket path or names no valid address. */
export function parseTerminalSocketPath(pathname: string): string | null {
  if (!pathname.startsWith(TERMINAL_SOCKET_PREFIX)) return null;
  let address: string;
  try {
    address = decodeURIComponent(pathname.slice(TERMINAL_SOCKET_PREFIX.length));
  } catch {
    return null;
  }
  return isTerminalAddress(address) ? address : null;
}

/** The first byte of every binary message on the terminal socket. */
export const Tag = {
  /** bridge → browser: bytes the terminal's program wrote (first paint included). */
  OUTPUT: 0,
  /** browser → bridge: what a person typed or pasted. Goes to core as DATA. */
  INPUT: 1,
  /** browser → bridge: replies the emulator generated by itself. Goes to core as AUTOMATIC_INPUT. */
  AUTOMATIC: 2,
} as const;
export type TagValue = (typeof Tag)[keyof typeof Tag];

/** `[tag][bytes…]` as one new buffer. */
export function tagMessage(tag: TagValue, bytes: Uint8Array): Uint8Array {
  const out = new Uint8Array(1 + bytes.length);
  out[0] = tag;
  out.set(bytes, 1);
  return out;
}

export type Tagged = { tag: TagValue; bytes: Uint8Array };

/** Split a binary message into its tag and the bytes after it (a view, not a copy); null for an empty message or an unknown tag. */
export function splitTagged(message: Uint8Array): Tagged | null {
  const tag = message[0];
  if (tag !== Tag.OUTPUT && tag !== Tag.INPUT && tag !== Tag.AUTOMATIC) return null;
  return { tag, bytes: message.subarray(1) };
}

/** Largest grid either side accepts. */
export const MAX_DIMENSION = 1000;

const Dimension = z.number().int().min(1).max(MAX_DIMENSION);
const Hex = z.string().regex(/^#[0-9a-fA-F]{6}$/);

/** What the viewer looks like: default colours as `#rrggbb` and the cell size in device pixels. Anything may be null (unknown). */
export const DisplaySchema = z.object({
  fg: Hex.nullable(),
  bg: Hex.nullable(),
  cursor: Hex.nullable(),
  cell: z.tuple([z.number().int().min(1).max(1000), z.number().int().min(1).max(1000)]).nullable(),
});

/** Most scrollback lines a view may ask for in its first paint. */
export const MAX_HISTORY = 100_000;

export const TerminalClientMessageSchema = z.discriminatedUnion("type", [
  /** Must be the first message. */
  z.object({ type: z.literal("attach"), cols: Dimension, rows: Dimension, history: z.number().int().min(0).max(MAX_HISTORY), display: DisplaySchema }),
  z.object({ type: z.literal("resize"), cols: Dimension, rows: Dimension }),
  z.object({ type: z.literal("focus"), focused: z.boolean() }),
  z.object({ type: z.literal("display"), display: DisplaySchema }),
  /** Bytes the emulator has parsed since its last `consumed`; only then does the bridge let core send more. */
  z.object({ type: z.literal("consumed"), bytes: z.number().int().min(1).max(2 ** 31) }),
]);

export const TerminalServerMessageSchema = z.discriminatedUnion("type", [
  /** Attached on core; output follows (binary), starting with the first paint. */
  z.object({ type: z.literal("attached"), cols: z.number(), rows: z.number(), automaticInput: z.boolean() }),
  /** The terminal ended; the socket closes right after (code 1000). */
  z.object({ type: z.literal("ended"), reason: z.string(), exitCode: z.number().nullable(), signal: z.number().nullable() }),
]);

export type Display = z.infer<typeof DisplaySchema>;
export type TerminalClientMessage = z.infer<typeof TerminalClientMessageSchema>;
export type TerminalServerMessage = z.infer<typeof TerminalServerMessageSchema>;

/** Close codes the bridge uses on a terminal socket; the close reason is a short English text the app may show. */
export const TerminalClose = {
  /** The terminal ended (an `ended` message came first). */
  ENDED: 1000,
  /** WebSocket level: a text message that is not valid UTF-8. The WebSocket library sends this close itself. */
  BAD_DATA: 1007,
  /** The browser sent something that breaks this protocol. */
  PROTOCOL: 1008,
  /** WebSocket level: a message over the 1 MiB limit. The WebSocket library sends this close itself. */
  TOO_BIG: 1009,
  /** The bridge failed. */
  INTERNAL: 1011,
  /** No `attach` message arrived in time. */
  NO_ATTACH: 4408,
  /** Core has no such terminal. */
  NOT_FOUND: 4404,
  /** The terminal is finished: nothing to attach to (an `ended` message came first). */
  FINISHED: 4410,
  /** The browser fell too far behind in consuming output. */
  TOO_SLOW: 4413,
  /** Core, or the machine the terminal lives on, cannot be reached, or the line to it dropped. Attach again when it is back. */
  CORE_UNAVAILABLE: 4502,
} as const;

export type TerminalParsed<T> = { ok: true; message: T } | { ok: false; error: string };

function parse<T>(text: string, schema: z.ZodType<T>): TerminalParsed<T> {
  let json: unknown;
  try {
    json = JSON.parse(text);
  } catch {
    return { ok: false, error: "not valid JSON" };
  }
  const r = schema.safeParse(json);
  return r.success ? { ok: true, message: r.data } : { ok: false, error: r.error.message };
}

export const parseTerminalClientMessage = (text: string): TerminalParsed<TerminalClientMessage> => parse(text, TerminalClientMessageSchema);
export const parseTerminalServerMessage = (text: string): TerminalParsed<TerminalServerMessage> => parse(text, TerminalServerMessageSchema);
export const encodeTerminalMessage = (message: TerminalClientMessage | TerminalServerMessage): string => JSON.stringify(message);
