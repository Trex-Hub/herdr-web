import net from "node:net";
import { ConnectionClosedError, CoreError } from "./errors.js";
import { encodeCredit, encodeFrame, FrameDecoder, FrameKind } from "./frame.js";
import type { CoreNotification, HelloResult, Methods, Terminal } from "./types.js";

const NEWLINE = 0x0a;

export interface ConnectionHandlers {
  /** `event`, `heartbeat` and `missed` notifications, from any channel. */
  onNotification?: (n: CoreNotification) => void;
  /** A channel other than 0 was closed by the core. */
  onChannelClosed?: (channel: number) => void;
  /** The connection ended; `error` is set when it was not a clean `close()`. */
  onClose?: (error?: Error) => void;
}

export interface ConnectOptions extends ConnectionHandlers {
  /** Unix socket path (named pipe on Windows). */
  path: string;
  connectTimeoutMs?: number;
  /** Treat the connection as dead after this long without any traffic. Core sends a heartbeat every 15 s. */
  idleTimeoutMs?: number;
  generation?: number;
  /** Abort a connection that is still in its handshake; `connect` then rejects at once. */
  signal?: AbortSignal;
}

interface Pending {
  resolve: (value: unknown) => void;
  reject: (reason: Error) => void;
  /** Runs when the reply arrives, before any frame after it is looked at. */
  onResult?: (result: unknown) => void;
}

/** Display facts a viewer reports (`Display` in core's schema). */
export interface DisplayFacts {
  fg: string | null;
  bg: string | null;
  cursor: string | null;
  /** Cell size in device pixels: width, height. */
  cell: [number, number] | null;
}

export interface AttachParams {
  /** `t7`, or `machine/t7`. */
  terminal: string;
  cols: number;
  rows: number;
  /** Scrollback lines to include in the first paint. */
  history?: number;
  display?: DisplayFacts;
}

export interface AttachResult {
  channel: number;
  terminal: Terminal;
  resize_notifications: boolean;
  /** The whole path accepts AUTOMATIC_INPUT (kind 6). */
  automatic_input: boolean;
}

/** How a stream ended: core's CLOSE reason, or the line to core dropping. */
export interface StreamEnd {
  /** `exited`, `killed`, `lost`, `server_stop`, ... as in the terminal record; `connection_lost` when the line to core dropped. */
  reason: string;
  exit_code: number | null;
  signal: number | null;
  /** The line to core dropped; nothing is known about the terminal. */
  connectionLost: boolean;
}

export interface AttachHandlers {
  /** Bytes from the terminal: first paint, then live output. They are owed back to core as CREDIT once consumed. */
  onData: (bytes: Buffer) => void;
  /** The stream is over (once). */
  onEnd: (end: StreamEnd) => void;
}

/** One attached viewer on a terminal. */
export interface Attachment {
  readonly result: AttachResult;
  /** Human input (DATA). */
  sendInput(bytes: Uint8Array): void;
  /** Replies the emulator generated by itself (AUTOMATIC_INPUT). Only when `result.automatic_input`. */
  sendAutomatic(bytes: Uint8Array): void;
  resize(cols: number, rows: number): void;
  focus(focused: boolean): void;
  facts(display: DisplayFacts): void;
  /** Tell core `bytes` of output were consumed. */
  credit(bytes: number): void;
  /** Bytes written to core's socket and not yet flushed. */
  readonly queuedBytes: number;
  /** Detach; no more calls are delivered. */
  detach(): void;
}

interface JsonRpcMessage {
  jsonrpc?: string;
  id?: number | string | null;
  method?: string;
  params?: unknown;
  result?: unknown;
  error?: { code: number; message: string; data?: { kind?: string; hint?: string } };
}

/**
 * One framed-mode connection to core. Calls run on channel 0 side by side and
 * are matched by id; notifications from any channel go to `onNotification`.
 */
export class CoreConnection {
  private readonly decoder = new FrameDecoder();
  private readonly pending = new Map<number, Pending>();
  private readonly lineBuffers = new Map<number, Buffer>();
  private readonly streams = new Map<number, AttachHandlers>();
  private nextId = 2; // 1 is the hello
  private closed = false;
  private lastRx = Date.now();
  private watchdog: NodeJS.Timeout | undefined;

  private constructor(
    private readonly socket: net.Socket,
    readonly hello: HelloResult,
    private readonly handlers: ConnectionHandlers,
    idleTimeoutMs: number,
  ) {
    socket.on("data", (chunk) => this.onData(chunk));
    socket.resume();
    socket.on("error", (err) => this.shutdown(new ConnectionClosedError(`socket error: ${err.message}`, { cause: err })));
    socket.on("close", () => this.shutdown(new ConnectionClosedError()));
    if (idleTimeoutMs > 0) {
      this.watchdog = setInterval(() => {
        if (Date.now() - this.lastRx > idleTimeoutMs) {
          this.shutdown(new ConnectionClosedError(`no traffic from core for ${idleTimeoutMs} ms`));
        }
      }, Math.max(250, Math.floor(idleTimeoutMs / 3)));
      this.watchdog.unref();
    }
    if (socket.destroyed) this.shutdown(new ConnectionClosedError());
  }

  /** Connect, send `hello` with `framed: true`, and return a connection already in framed mode. */
  static async connect(opts: ConnectOptions): Promise<CoreConnection> {
    const socket = net.createConnection(opts.path);
    socket.on("error", () => {}); // errors are reported by the handshake and the connection; never uncaught
    const timeoutMs = opts.connectTimeoutMs ?? 5000;
    try {
      const { hello, rest } = await handshake(socket, timeoutMs, opts.generation ?? 1, opts.signal);
      const conn = new CoreConnection(socket, hello, opts, opts.idleTimeoutMs ?? 45_000);
      // The core may already have sent frames in the same read as the hello reply.
      if (rest.length > 0) conn.onData(rest);
      return conn;
    } catch (err) {
      socket.destroy();
      throw err;
    }
  }

  call<M extends keyof Omit<Methods, "hello">>(method: M, params: Methods[M]["params"]): Promise<Methods[M]["result"]>;
  call(method: string, params: unknown): Promise<unknown>;
  call(method: string, params: unknown): Promise<unknown> {
    return this.request(method, params);
  }

  private request(method: string, params: unknown, onResult?: (result: unknown) => void): Promise<unknown> {
    if (this.closed) return Promise.reject(new ConnectionClosedError());
    const id = this.nextId++;
    return new Promise((resolve, reject) => {
      this.pending.set(id, { resolve, reject, ...(onResult && { onResult }) });
      const body = Buffer.from(JSON.stringify({ jsonrpc: "2.0", id, method, params }));
      this.socket.write(encodeFrame(0, FrameKind.DATA, body), (err) => {
        if (err && this.pending.delete(id)) reject(new ConnectionClosedError(`write failed: ${err.message}`, { cause: err }));
      });
    });
  }

  /**
   * Attach to a live terminal on this connection and stream its bytes. The core must advertise
   * `automatic_input`, or attach is refused: replies must not look like typing.
   */
  async attach(params: AttachParams, handlers: AttachHandlers): Promise<Attachment> {
    const base = { terminal: params.terminal, cols: params.cols, rows: params.rows, history: params.history ?? 0, ...(params.display && { display: params.display }) };
    let channel = -1;
    let ended = false;
    const result = (await this.request("terminal.attach", base, (r) => {
      // Registered before the next frame is read: the first paint can arrive in the same read as the reply.
      channel = (r as AttachResult).channel;
      this.streams.set(channel, {
        onData: handlers.onData,
        onEnd: (end) => {
          ended = true;
          handlers.onEnd(end);
        },
      });
    })) as AttachResult;
    return this.attachment(channel, result, () => !ended);
  }

  private attachment(channel: number, result: AttachResult, isOpen: () => boolean): Attachment {
    const conn = this;
    let open = true;
    const send = (kind: number, payload: Uint8Array) => {
      if (open && isOpen() && !this.closed) this.socket.write(encodeFrame(channel, kind, payload));
    };
    return {
      result,
      sendInput: (bytes) => send(FrameKind.DATA, bytes),
      sendAutomatic: (bytes) => send(result.automatic_input ? FrameKind.AUTOMATIC_INPUT : FrameKind.DATA, bytes),
      resize: (cols, rows) => {
        const p = Buffer.allocUnsafe(4);
        p.writeUInt16LE(cols, 0);
        p.writeUInt16LE(rows, 2);
        send(FrameKind.RESIZE, p);
      },
      focus: (focused) => send(FrameKind.FOCUS, Buffer.from([focused ? 1 : 0])),
      facts: (display) => send(FrameKind.FACTS, Buffer.from(JSON.stringify(display))),
      credit: (bytes) => {
        if (!open || !isOpen() || this.closed || bytes <= 0) return;
        this.socket.write(encodeCredit(channel, bytes));
      },
      get queuedBytes() {
        return conn.socket.writableLength;
      },
      detach: () => {
        if (!open) return;
        open = false;
        this.streams.delete(channel);
        if (isOpen() && !this.closed) this.socket.write(encodeFrame(channel, FrameKind.CLOSE, Buffer.alloc(0)));
      },
    } as Attachment;
  }

  /** Bytes written to the socket and not yet flushed to the kernel. */
  get queuedBytes(): number {
    return this.socket.writableLength;
  }

  close(): void {
    this.shutdown(undefined);
  }

  get isClosed(): boolean {
    return this.closed;
  }

  private onData(chunk: Buffer): void {
    this.lastRx = Date.now();
    let frames;
    try {
      frames = this.decoder.push(chunk);
    } catch (err) {
      this.shutdown(err instanceof Error ? err : new Error(String(err)));
      return;
    }
    for (const frame of frames) {
      if (this.closed) return;
      const stream = this.streams.get(frame.channel);
      if (frame.kind === FrameKind.DATA) {
        if (frame.channel === 0) this.handleMessage(frame.payload);
        else if (stream) stream.onData(frame.payload);
        else this.handleStream(frame.channel, frame.payload);
      } else if (frame.kind === FrameKind.CLOSE && frame.channel !== 0) {
        if (stream) {
          this.streams.delete(frame.channel);
          stream.onEnd(parseEnd(frame.payload));
        } else {
          this.lineBuffers.delete(frame.channel);
          this.handlers.onChannelClosed?.(frame.channel);
        }
      }
    }
  }

  /** Channel 0: one JSON-RPC message per DATA frame. */
  private handleMessage(payload: Buffer): void {
    if (payload.toString("utf8").trim() === "") return; // nothing to parse; same as a blank line on the event channel
    let msg: JsonRpcMessage;
    try {
      msg = JSON.parse(payload.toString("utf8")) as JsonRpcMessage;
    } catch (err) {
      this.shutdown(new Error(`invalid JSON from core: ${(err as Error).message}`));
      return;
    }
    if (typeof msg.id === "number" && this.pending.has(msg.id)) {
      const p = this.pending.get(msg.id)!;
      this.pending.delete(msg.id);
      if (msg.error) p.reject(new CoreError(msg.error));
      else {
        p.onResult?.(msg.result);
        p.resolve(msg.result);
      }
    } else if (msg.method) {
      this.handlers.onNotification?.({ method: msg.method, params: msg.params } as CoreNotification);
    }
  }

  /** Other channels (events): JSON lines. Credit the bytes back so the stream keeps flowing. */
  private handleStream(channel: number, payload: Buffer): void {
    if (payload.length > 0) this.socket.write(encodeCredit(channel, payload.length));
    let buf = Buffer.concat([this.lineBuffers.get(channel) ?? Buffer.alloc(0), payload]);
    let nl: number;
    while ((nl = buf.indexOf(NEWLINE)) >= 0) {
      const line = buf.subarray(0, nl).toString("utf8").trim();
      buf = buf.subarray(nl + 1);
      if (line) this.handleMessage(Buffer.from(line));
      if (this.closed) return;
    }
    this.lineBuffers.set(channel, Buffer.from(buf));
  }

  private shutdown(error: Error | undefined): void {
    if (this.closed) return;
    this.closed = true;
    if (this.watchdog) clearInterval(this.watchdog);
    this.socket.destroy();
    const reason = error ?? new ConnectionClosedError("connection closed by client");
    for (const p of this.pending.values()) p.reject(reason);
    this.pending.clear();
    const streams = [...this.streams.values()];
    this.streams.clear();
    for (const h of streams) h.onEnd({ reason: "connection_lost", exit_code: null, signal: null, connectionLost: true });
    this.handlers.onClose?.(error);
  }
}

function parseEnd(payload: Buffer): StreamEnd {
  try {
    const j = JSON.parse(payload.toString("utf8")) as { reason?: unknown; exit_code?: unknown; signal?: unknown };
    return {
      reason: typeof j.reason === "string" ? j.reason : "closed",
      exit_code: typeof j.exit_code === "number" ? j.exit_code : null,
      signal: typeof j.signal === "number" ? j.signal : null,
      connectionLost: false,
    };
  } catch {
    return { reason: "closed", exit_code: null, signal: null, connectionLost: false };
  }
}

/** Plain-mode hello: one JSON line out, one line back; bytes after it belong to framed mode. */
function handshake(
  socket: net.Socket,
  timeoutMs: number,
  generation: number,
  signal: AbortSignal | undefined,
): Promise<{ hello: HelloResult; rest: Buffer }> {
  return new Promise((resolve, reject) => {
    let buf: Buffer = Buffer.alloc(0);
    const timer = setTimeout(() => fail(new ConnectionClosedError(`no hello reply within ${timeoutMs} ms`)), timeoutMs);
    const cleanup = () => {
      clearTimeout(timer);
      signal?.removeEventListener("abort", onAbort);
      socket.off("data", onData);
      socket.off("error", onError);
      socket.off("close", onEnd);
    };
    const fail = (err: Error) => {
      cleanup();
      reject(err);
    };
    const onAbort = () => fail(new ConnectionClosedError("connect aborted"));
    const onError = (err: Error) => fail(new ConnectionClosedError(`cannot connect: ${err.message}`, { cause: err }));
    const onEnd = () => fail(new ConnectionClosedError("core closed the connection during hello"));
    const onData = (chunk: Buffer) => {
      buf = Buffer.concat([buf, chunk]);
      const nl = buf.indexOf(NEWLINE);
      if (nl < 0) return;
      cleanup();
      socket.pause(); // hold further bytes until the connection takes over
      let msg: JsonRpcMessage;
      try {
        msg = JSON.parse(buf.subarray(0, nl).toString("utf8")) as JsonRpcMessage;
      } catch (err) {
        reject(new Error(`invalid hello reply: ${(err as Error).message}`));
        return;
      }
      if (msg.error) reject(new CoreError(msg.error));
      else if (!(msg.result as HelloResult | undefined)?.framed) reject(new Error("core did not switch to framed mode"));
      else resolve({ hello: msg.result as HelloResult, rest: Buffer.from(buf.subarray(nl + 1)) });
    };
    if (signal?.aborted) return onAbort();
    signal?.addEventListener("abort", onAbort, { once: true });
    socket.on("error", onError);
    socket.on("close", onEnd);
    socket.on("data", onData);
    socket.on("connect", () => {
      const hello = { jsonrpc: "2.0", id: 1, method: "hello", params: { framed: true, generation } };
      socket.write(JSON.stringify(hello) + "\n");
    });
  });
}
